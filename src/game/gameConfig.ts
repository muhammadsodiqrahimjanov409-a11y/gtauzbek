export function getDefaultVehicleTuning(vehicleId: VehicleId): VehicleCustomTuning {
  const isHeavy =
    vehicleId === 'labo' ||
    vehicleId === 'gazel' ||
    vehicleId === 'isuzu' ||
    vehicleId === 'howo' ||
    vehicleId === 'fura' ||
    vehicleId === 'kamaz' ||
    vehicleId === 'zil' ||
    vehicleId === 'excavator';
  const isSport =
    vehicleId === 'sport' ||
    vehicleId === 'supercar' ||
    vehicleId === 'hypercar' ||
    vehicleId === 'track' ||
    vehicleId === 'drift' ||
    vehicleId === 'roadster' ||
    vehicleId === 'electric_gt';
  const isLux = vehicleId === 'limo' || vehicleId === 'lux_suv' || vehicleId === 'gt_tourer' || vehicleId === 'classic';

  let rimStyle: RimStyleId = 'classic';
  if (isHeavy || vehicleId === 'pickup' || vehicleId === 'armored') {
    rimStyle = 'heavy';
  } else if (isSport) {
    rimStyle = 'sport';
  } else if (isLux) {
    rimStyle = 'luxury';
  }

  let cargoType: CargoLoadId = 'empty';
  if (vehicleId === 'fura' || vehicleId === 'labo' || vehicleId === 'pickup') cargoType = 'wood';
  else if (vehicleId === 'kamaz' || vehicleId === 'isuzu') cargoType = 'concrete';
  else if (vehicleId === 'zil' || vehicleId === 'gazel') cargoType = 'steel';
  else if (vehicleId === 'excavator' || vehicleId === 'howo') cargoType = 'gravel';

  const interiorColor = isLux
    ? '#B45309'
    : vehicleId === 'supercar' || vehicleId === 'sport'
      ? '#991B1B'
      : '#1E293B';

  const rimColor =
    vehicleId === 'excavator' || vehicleId === 'howo'
      ? '#F59E0B'
      : vehicleId === 'kamaz' || vehicleId === 'zil' || vehicleId === 'armored'
        ? '#111827'
        : '#E2E8F0';

  return {
    tireColor: vehicleId === 'classic' ? '#F8FAFC' : '#171717',
    interiorColor,
    rimColor,
    rimStyle,
    cargoType,
  };
}

