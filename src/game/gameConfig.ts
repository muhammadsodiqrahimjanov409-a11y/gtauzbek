export function detectDistrict(x: number, z: number): DistrictId {
  if (Math.abs(x) > 368 || Math.abs(z) > 368) {
    return 'highway';
  }
  if (x >= -130 && x <= 130 && z >= -368 && z < 0) {
    return 'downtown';
  }
  if (x >= -260 && x < 0 && z >= 0 && z < 130) {
    return 'park';
  }
  if (x < 0 && z >= 130) {
    return 'residential';
  }
  if (x >= 130 && z < 0) {
    return 'industrial';
  }
  if (x >= 0 && z >= 0) {
    return 'commercial';
  }
  return 'industrial';
}

